"""Generated read-only Markdown views per project: queue, questions and decisions."""
import os
import re
from pathlib import Path

from . import config, db

HEADER = "<!-- generated by HaiveQueen, do not edit -->"
VIEW_KINDS = ("queue", "questions", "decisions")


def _cell(value) -> str:
    """Make a value safe for a Markdown table cell."""
    return str(value if value is not None else "").replace("|", "\\|").replace("\r", " ").replace("\n", " ")


def _table(head, body) -> list:
    """Return the lines of a Markdown table."""
    lines = ["| " + " | ".join(head) + " |", "|" + "---|" * len(head)]
    lines += ["| " + " | ".join(_cell(c) for c in row) + " |" for row in body]
    return lines


def _status_text(row) -> str:
    """Return the status of a queue row; a withdrawn row also shows the original status word kept at the start of its note."""
    if row["status"] == "withdrawn":
        word = re.match(r"[^\s(|,]+", str(row["note"] or ""))
        if word:
            return f"withdrawn ({word.group(0)})"
    return row["status"]


def render_queue(conn, project) -> str:
    """Render the integration queue of a project."""
    body = [(r["branch"], r["tip"], _status_text(r), r["plan_path"], r["note"], r["updated_at"])
            for r in db.queue_rows(conn, project)]
    lines = [HEADER, "", f"# Integration queue: {project}", ""]
    lines += _table(["Branch", "Tip", "Status", "Plan", "Note", "Updated"], body)
    return "\n".join(lines) + "\n"


# Render visible open and answered questions for a project.
def render_questions(conn, project) -> str:
    """Render open and answered questions of a project."""
    qs = db.open_questions(conn, project)
    lines = [HEADER, "", f"# Questions: {project}", "", "## Open", ""]
    lines += _table(["Id", "Plan", "Item", "Question", "Recommendation", "Asked"],
                    [(q["id"], q["plan_path"], q["item"], q["question"], q["recommendation"], q["created_at"])
                     for q in qs if q["status"] == "open"])
    lines += ["", "## Answered", ""]
    lines += _table(["Id", "Plan", "Item", "Question", "Answer", "By", "Answered"],
                    [(q["id"], q["plan_path"], q["item"], q["question"], q["answer"], q["answered_by"],
                      q["answered_at"]) for q in qs if q["status"] not in ("open", "fault_check")])
    return "\n".join(lines) + "\n"


def render_decisions(conn, project) -> str:
    """Render the active decisions of a project (rule and superseded ones are not shown)."""
    rows = db.rows(conn, "SELECT * FROM decisions WHERE project=? AND status='active' ORDER BY id", (project,))
    lines = [HEADER, "", f"# Decisions: {project}", ""]
    lines += _table(["Id", "Time", "Source", "Plan", "Decision"],
                    [(r["id"], r["ts"], r["source"], r["plan_path"], r["text"]) for r in rows])
    return "\n".join(lines) + "\n"


RENDERERS = {"queue": render_queue, "questions": render_questions, "decisions": render_decisions}


def write_if_changed(path: Path, text: str) -> bool:
    """Write text atomically (temp file + replace) unless the file already has this content; True if written."""
    data = text.encode("utf-8")
    if path.is_file() and path.read_bytes() == data:
        return False
    path.parent.mkdir(parents=True, exist_ok=True)
    tmp = path.with_name(path.name + ".tmp")
    tmp.write_bytes(data)
    os.replace(tmp, path)
    return True


def write_views(conn, project, workspace=None) -> dict:
    """Write the configured views of a project; returns {kind: path} of the files that changed.

    Paths come from project.toml [views]; relative paths are taken against the workspace; empty = no view.
    """
    if workspace is None:
        row = conn.execute("SELECT workspace FROM projects WHERE name=?", (project,)).fetchone()
        workspace = row["workspace"] if row else None
    if not workspace:
        return {}
    ws = Path(workspace)
    views = config.load_project(ws)["views"]
    changed = {}
    for kind in VIEW_KINDS:
        rel = views.get(kind) or ""
        if not rel:
            continue
        path = Path(rel)
        if not path.is_absolute():
            path = ws / path
        if write_if_changed(path, RENDERERS[kind](conn, project)):
            changed[kind] = str(path)
    return changed
