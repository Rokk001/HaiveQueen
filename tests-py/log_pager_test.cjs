const assert=require('node:assert/strict');
const {LogPager}=require('../haivequeen/web-client.js');
const pager=new LogPager();
assert.equal(pager.request().cursor,'null');
pager.accept({run:'one',output:'first\n',cursor:[100,0],more:false});
pager.accept({run:'one',output:'',cursor:[100,0],more:false});
assert.equal(pager.text,'first\n','empty live polls must retain visible output');
pager.accept({run:'one',output:'second\n',cursor:[200,0],more:false});
assert.equal(pager.text,'first\nsecond\n');
pager.accept({run:'one',output:'x'.repeat(70000),cursor:[300,0],more:true});
assert.equal(pager.text.length,65536,'live view memory must remain bounded');
pager.accept({run:'two',output:'new',cursor:[50,0],more:false,reset:true,source:''});
assert.equal(pager.text,'new','new attempt must not mix with the previous run');
pager.source='selected';pager.restart();
assert.equal(pager.request().source,'selected');
assert.equal(pager.text,'');
pager.accept({run:'two',output:'partial reference',cursor:[30,0],more:true,continuation:'signed-tail'});
pager.restart(pager.cursor);
assert.equal(pager.request().continuation,'signed-tail','manual next page preserves reference discovery');
pager.restart();
assert.equal(pager.request().continuation,'','start of log clears previous discovery context');
console.log('Log pager tests passed');
