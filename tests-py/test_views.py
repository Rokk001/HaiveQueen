"""Tests of the generated Markdown views."""
import os
import sys
import tempfile
import unittest
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))
from haivequeen import db, views  # noqa: E402


class ViewsTest(unittest.TestCase):
    """Views are written with the marker line, only when the content changes."""

    def setUp(self):
        """Create a temp workspace with project.toml and a temp database."""
        self.tmp = tempfile.TemporaryDirectory()
        root = Path(self.tmp.name)
        self.ws = root / "ws"
        (self.ws / ".haivequeen").mkdir(parents=True)
        (self.ws / ".haivequeen" / "project.toml").write_text(
            'name = "demo"\n[views]\nqueue = "views/queue.md"\nquestions = "views/questions.md"\n'
            'decisions = ""\n', encoding="utf-8")
        self.conn = db.connect(root / "data" / "haivequeen.db")
        db.upsert_project(self.conn, "demo", str(self.ws), "cyan", 0)

    def tearDown(self):
        """Close the database and remove the temp folder."""
        self.conn.close()
        self.tmp.cleanup()

    def test_first_line_and_empty_path(self):
        """Configured views start with the marker; an empty path writes nothing."""
        db.add_ready(self.conn, "demo", "b1", "abc", "p.md", "n|ote")
        db.add_question(self.conn, "demo", "p.md", "I1", "Which?", "A")
        written = views.write_views(self.conn, "demo")
        self.assertEqual(sorted(written), ["questions", "queue"])
        for kind in written:
            first = Path(written[kind]).read_text(encoding="utf-8").splitlines()[0]
            self.assertEqual(first, "<!-- generated by HaiveQueen, do not edit -->")
        self.assertIn("n\\|ote", (self.ws / "views" / "queue.md").read_text(encoding="utf-8"))
        self.assertFalse((self.ws / "views" / "decisions.md").exists())

    def test_no_change_no_write(self):
        """A second run with unchanged data does not touch the files; a change rewrites them."""
        views.write_views(self.conn, "demo")
        q = self.ws / "views" / "queue.md"
        os.utime(q, (1000000000, 1000000000))
        self.assertEqual(views.write_views(self.conn, "demo"), {})
        self.assertEqual(int(q.stat().st_mtime), 1000000000)
        db.add_ready(self.conn, "demo", "b2", "def", "p.md", "")
        self.assertEqual(list(views.write_views(self.conn, "demo")), ["queue"])
        self.assertIn("b2", q.read_text(encoding="utf-8"))
        self.assertEqual([p.name for p in q.parent.iterdir() if p.name.endswith(".tmp")], [])

    def test_decisions_view(self):
        """The decisions view lists answered questions."""
        qid = db.add_question(self.conn, "demo", "p.md", "I1", "Which?", "A")
        db.answer_question(self.conn, qid, "A", "owner")
        text = views.render_decisions(self.conn, "demo")
        self.assertTrue(text.startswith(views.HEADER + "\n"))
        self.assertIn("Which? -> A", text)

    def test_decisions_view_shows_only_active(self):
        """A decision with status rule or superseded is not in the decisions view."""
        db.add_question(self.conn, "demo", "p.md", "I1", "Keep?", "A")
        db.add_question(self.conn, "demo", "p.md", "I2", "Drop?", "B")
        db.answer_question(self.conn, 1, "A", "owner")
        db.answer_question(self.conn, 2, "B", "owner")
        self.conn.execute("UPDATE decisions SET status='superseded' WHERE text LIKE 'Drop?%'")
        text = views.render_decisions(self.conn, "demo")
        self.assertIn("Keep? -> A", text)
        self.assertNotIn("Drop? -> B", text)


if __name__ == "__main__":
    unittest.main()
